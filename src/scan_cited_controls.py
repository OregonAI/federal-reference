#!/usr/bin/env python3
"""Derive which SP 800-53 controls the documents held in THIS corpus cite (#42, ADR-0003).

    python3 src/scan_cited_controls.py            # write _meta/cited-controls/nist-sp-800-53-r5.yml
    python3 src/scan_cited_controls.py --check    # exit 1 if the committed list is stale

The import list is DERIVED, never curated: ADR-0003's rule is "split only what is cited". The
scan covers every held instrument that names 800-53 at all (the issue's own test), except the
NIST documents themselves -- a publication's own text cites its own controls constantly, and
counting that would make every control "demanded" the moment it was held.

DIFFERENCES FROM THE ISSUE'S SNAPSHOT SCAN (228 controls, 3,758 tokens), measured 2026-11-12 on
the same held set minus two documents added since:
  * the issue's regex matched inside NIST CSF subcategories (`PR.AC-3`, `PR.IP-3`), which are not
    800-53 controls; this one does not (nist_controls.CONTROL_TOKEN);
  * `arc-ampe` and `cisa-cpg` were ingested after the issue was written and both cite 800-53.
Run the issue's own scan with `arc-ampe` and `cisa-cpg` excluded and it returns exactly
228 / 3,758 -- so the difference is those two causes and nothing else.

THE SCAN LOOKS ONLY AT THIS REPOSITORY, which is why --check runs in CI (unlike
scan_cited_sections.py, which needs sibling checkouts CI cannot reach). A new held document that
cites a control not yet split turns the gate red.
"""
from __future__ import annotations

import argparse
import sys
from collections import Counter
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
from nist_controls import (  # noqa: E402
    MENTIONS_800_53, PUBLICATION_ID, catalog_ids, natural_key, scan_text,
)

ROOT = Path(__file__).resolve().parent.parent
INSTRUMENTS = ROOT / "instruments"
SNAPSHOT = ROOT / "_meta" / "snapshots" / f"{PUBLICATION_ID}.txt"
OUT = ROOT / "_meta" / "cited-controls" / f"{PUBLICATION_ID}.yml"
NIST_KINDS = {"nist_publication", "nist_control"}

HEADER = """\
# GENERATED by src/scan_cited_controls.py -- do not hand-edit; `--check` is a CI gate.
#
# The SP 800-53 Rev. 5 controls cited by documents held in this corpus (#42, ADR-0003: split only
# what is cited). `controls` is the split list src/split_nist_controls.py reads. `citations`
# counts every control token in a scanned document (an enhancement `AC-2(1)` counts toward its
# base `ac-2`; `enhancement_citations` is how many of them were enhancement forms). A scanned
# document is any held instrument that names 800-53, excluding the NIST documents themselves.
# `not_in_catalog` are tokens in scanned documents that are NOT a control the Rev. 5 catalog
# holds (e.g. a family-shaped id used by a citing document's own numbering): reported, never
# split, and never silently dropped.
"""


def derive(held: dict[str, tuple[str, str]], catalog: set[str]) -> dict:
    """`held` is {document id: (instrument_kind, full file text)}. Pure."""
    per_doc: dict[str, Counter] = {}
    enh_total: Counter = Counter()
    scanned: list[str] = []
    for doc_id in sorted(held):
        kind, text = held[doc_id]
        # The BODY only: a document's own front matter now carries the `related` edge to the
        # publication, which must not make it "a document that names 800-53".
        body = text.split("\n---\n", 1)[1] if text.startswith("---\n") and "\n---\n" in text else text
        if kind in NIST_KINDS or not MENTIONS_800_53.search(body):
            continue
        scanned.append(doc_id)
        base, enh = scan_text(body)
        per_doc[doc_id] = base
        enh_total.update({k.split("(", 1)[0]: v for k, v in enh.items()})
    total: Counter = Counter()
    for c in per_doc.values():
        total.update(c)
    controls = [{
        "id": cid,
        "control": f"{cid.split('-')[0].upper()}-{cid.split('-')[1]}",
        "citations": total[cid],
        "enhancement_citations": enh_total[cid],
        "documents": {d: per_doc[d][cid] for d in scanned if per_doc[d][cid]},
    } for cid in sorted(total, key=natural_key) if cid in catalog]
    return {
        "publication": PUBLICATION_ID,
        "documents_scanned": scanned,
        "distinct_controls": len(controls),
        "total_citations": sum(c["citations"] for c in controls),
        "not_in_catalog": {cid: total[cid] for cid in sorted(total, key=natural_key)
                           if cid not in catalog},
        "controls": controls,
    }


def load_held() -> dict[str, tuple[str, str]]:
    held = {}
    for path in sorted(INSTRUMENTS.glob("*.md")):
        text = path.read_text(encoding="utf-8", errors="ignore")
        fm = yaml.safe_load(text.split("---", 2)[1]) or {}
        held[fm.get("id", path.stem)] = (fm.get("instrument_kind", ""), text)
    return held


def render(result: dict) -> str:
    return HEADER + yaml.safe_dump(result, sort_keys=False, allow_unicode=True, width=100)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    catalog = catalog_ids(SNAPSHOT.read_text(encoding="utf-8"))
    out = render(derive(load_held(), catalog))
    if args.check:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != out:
            print(f"{OUT.relative_to(ROOT)} is stale -- run: python3 src/scan_cited_controls.py",
                  file=sys.stderr)
            return 1
        print(f"{OUT.relative_to(ROOT)} is current.")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(out, encoding="utf-8")
    res = yaml.safe_load(out)
    print(f"wrote {OUT.relative_to(ROOT)}: {res['distinct_controls']} controls, "
          f"{res['total_citations']} citations from {len(res['documents_scanned'])} documents; "
          f"{len(res['not_in_catalog'])} token(s) not in the catalog")
    return 0


if __name__ == "__main__":
    sys.exit(main())
